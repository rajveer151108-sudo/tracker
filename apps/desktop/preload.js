const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("tracker", {
  nowPlaying: () => ipcRenderer.invoke("now-playing"),
  lyrics: (info) => ipcRenderer.invoke("lyrics", info),
  genre: (info) => ipcRenderer.invoke("genre", info),
  lyricsDiag: (info) => ipcRenderer.invoke("lyrics-diag", info),
  screenCaptureStatus: () => ipcRenderer.invoke("screen-capture-status"),
  systemAudioSource: () => ipcRenderer.invoke("system-audio-source"),
  control: (action) => ipcRenderer.invoke("control", action),
  seek: (positionSec) => ipcRenderer.invoke("seek", positionSec),
  setVolume: (volume) => ipcRenderer.invoke("volume-set", volume),
  getSettings: () => ipcRenderer.invoke("settings-get"),
  setSettings: (patch) => ipcRenderer.send("settings-set", patch),
  onSettings: (cb) => ipcRenderer.on("settings", (_e, s) => cb(s)),
  songPresetGet: (key) => ipcRenderer.invoke("song-preset-get", key),
  songPresetSave: (payload) => ipcRenderer.invoke("song-preset-set", payload),
  songPresetRemove: (key) => ipcRenderer.invoke("song-preset-remove", key),
  onAuthRestored: (cb) => ipcRenderer.on("auth-restored", () => cb()),
  sendGlow: (p) => ipcRenderer.send("glow-update", p),
  previewGlow: (p) => ipcRenderer.send("glow-preview", p),
  sendBeat: (v) => ipcRenderer.send("beat", v),
  toggleFullscreen: () => ipcRenderer.send("fullscreen-toggle"),
  playUri: (uri, ctx) => ipcRenderer.invoke("play-uri", uri, ctx),
  historyGet: () => ipcRenderer.invoke("history-get"),
  historyAdd: (t) => ipcRenderer.send("history-add", t),
  spLogin: () => ipcRenderer.invoke("sp-login"),
  spLogout: () => ipcRenderer.invoke("sp-logout"),
  spStatus: () => ipcRenderer.invoke("sp-status"),
  spApi: (request) => ipcRenderer.invoke("sp-api", request),
  spotifyPublicPlaylist: (playlistId) => ipcRenderer.invoke("spotify-public-playlist", playlistId),
  spotifyCanvas: (trackUri) => ipcRenderer.invoke("spotify-canvas", trackUri),
  connectTracker: (session) => ipcRenderer.invoke("tracker-connect", session),
  disconnectTracker: () => ipcRenderer.invoke("tracker-disconnect"),
  trackerSyncStatus: () => ipcRenderer.invoke("tracker-sync-status"),
  observeForTracker: (track) => ipcRenderer.send("tracker-observe", track),
  setPlaybackActive: (active) => ipcRenderer.send("playback-active", active === true),
  onTrackerSyncStatus: (cb) => ipcRenderer.on("tracker-sync-status", (_e, status) => cb(status)),
  minimize: () => ipcRenderer.send("win-minimize"),
  quit: () => ipcRenderer.send("win-close"),
  openTrackerExternal: () => ipcRenderer.send("tracker-open-external"),
  onFullscreen: (cb) => ipcRenderer.on("fullscreen", (_e, on) => cb(on)),
});
